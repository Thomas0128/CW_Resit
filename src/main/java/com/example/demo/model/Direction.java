package com.example.demo.model;

/**
 * Represents the four possible tile movement directions
 */
public enum Direction {

    /**
     * Moves tiles towards the top of the board
     */
    UP,

    /**
     * Moves tiles towards the bottom of the board
     */
    DOWN,

    /**
     * Moves tiles towards the left side of the board
     */
    LEFT,

    /**
     * Moves tiles towards the right side of the board
     */
    RIGHT
}
